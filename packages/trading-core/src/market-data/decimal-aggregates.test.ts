import { expect, it } from "vitest";
import { sumDecimals } from "./read";

it.each([
  [["100", "200"], "300"],
  [["1.5", "2.5"], "4"],
  [["1.5", "2.25"], "3.75"],
  [["82191.580763915510256221435514", "0"], "82191.580763915510256221435514"],
  [["295374.775097744356196433467441390498857744039", "0"], "295374.775097744356196433467441390498857744039"],
  [["82191.580763915510256221435514", "100.000000000000000000000000001"], "82291.580763915510256221435514001"],
  [["0"], "0"],
  [["0", "0", "0"], "0"],
  [["1.500", "2.500"], "4"],
  [["100", "0.5", "0.25"], "100.75"],
  [
    ["27397.193587971836752073811838", "27397.193587971836752073811838", "27397.193587971836752073811838"],
    "82191.580763915510256221435514",
  ],
  [["-1.25", "0.5"], "-0.75"],
])("preserves exact aggregates for %j", (values, expected) => {
  expect(sumDecimals(values as string[])).toBe(expected);
});
